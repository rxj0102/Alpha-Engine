"""Render the README results block from results/metrics.json.

python scripts/render_readme.py          rewrite the block
python scripts/render_readme.py --check  exit 1 if the README is out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARK = "<!-- {name}:start (generated by scripts/render_readme.py, do not edit by hand) -->"
END = "<!-- {name}:end -->"
ORDER = ["1/N", "Inverse volatility", "Momentum", "Carry (bonds)", "Momentum + carry", "ML", "US market"]
FORECAST = ["Momentum", "Carry (bonds)", "Momentum + carry", "ML"]


def pct(x, d=1):
    return f"{100 * x:.{d}f}%"


def load() -> dict:
    return json.loads((ROOT / "results" / "metrics.json").read_text())


def headline(m: dict) -> str:
    """The summary at the top of the README. Its wording assumes the checks below hold."""
    s, summ, ic, rb, per = m["sample"], m["summary"], m["ic"], m["robustness"], m["ic_periods"]
    diffs = [d for d in m["sharpe_diffs"] if d["b"] == "1/N"]
    labs = list(per)
    checks = {
        "no forecast strategy differs from 1/N at the 5% level": min(d["p_value"] for d in diffs) > 0.05,
        "no forecast strategy has a higher Sharpe ratio than 1/N": all(d["diff"] < 0 for d in diffs),
        "the ML rank IC is positive with t above 2": ic["ML"]["t_stat"] > 2,
        "ML beats 1/N before costs": rb["no costs"]["ML"] > rb["no costs"]["1/N"],
        "ML IC is lower after 2010 than before": max(per[labs[2]]["ML"], per[labs[3]]["ML"]) < min(per[labs[0]]["ML"], per[labs[1]]["ML"]),
    }
    failed = [k for k, ok in checks.items() if not ok]
    if failed:
        raise SystemExit("The README summary no longer matches the results; rewrite headline() in "
                         "scripts/render_readme.py. Failed: " + "; ".join(failed))
    return (
        f"**Answer.** Over {s['years']:.0f} years out of sample ({s['first_day'][:4]} to {s['last_day'][:4]}, "
        f"{s['n_rebalances']} monthly rebalances), no. Every source of views ends up with a lower Sharpe ratio than the "
        f"1/N portfolio it starts from: 1/N {summ['1/N']['sharpe']:.2f}, momentum {summ['Momentum']['sharpe']:.2f}, "
        f"momentum plus carry {summ['Momentum + carry']['sharpe']:.2f}, ML {summ['ML']['sharpe']:.2f}. None of the "
        f"differences is statistically significant (smallest p = {min(d['p_value'] for d in diffs):.2f}).\n\n"
        f"The ML model is not noise. It ranks the 13 assets better than chance (mean rank IC {ic['ML']['mean']:.3f}, "
        f"t = {ic['ML']['t_stat']:.1f}), slightly ahead of momentum ({ic['Momentum']['mean']:.3f}, t = "
        f"{ic['Momentum']['t_stat']:.1f}), and before costs its portfolio has a Sharpe ratio of "
        f"{rb['no costs']['ML']:.2f} against {rb['no costs']['1/N']:.2f} for 1/N. Two things undo it. It turns over "
        f"{summ['ML']['turnover_ann']:.1f} times its capital a year, against {summ['Momentum']['turnover_ann']:.1f} for "
        f"momentum, and trading costs take the whole gain. And the skill is old: the mean IC was "
        f"{per[labs[0]]['ML']:.2f} in {labs[0]} and {per[labs[1]]['ML']:.2f} in {labs[1]}, then "
        f"{per[labs[2]]['ML']:.2f} in {labs[2]} and {per[labs[3]]['ML']:.2f} since 2020."
    )


def render(m: dict) -> str:
    s, c, summ = m["sample"], m["config"], m["summary"]
    L = []
    L.append(f"Out-of-sample period {s['first_day']} to {s['last_day']}: {s['n_days']} trading days, "
             f"{s['n_rebalances']} month-end rebalances, {s['years']:.1f} years. Data start {c['data_start']}; "
             f"the first {c['min_train_months']} months train the first model. Returns are after trading costs. "
             f"Sharpe ratios use daily returns in excess of the Treasury bill rate, with a 95% block bootstrap "
             f"interval ({c['n_bootstrap']} draws, {c['block']} day blocks). The ML training set grows from "
             f"{s['training_rows_first']} asset-months at the first forecast to {s['panel_rows']} at the last.")
    L.append("")
    L.append("**Performance**")
    L.append("")
    L.append("| Portfolio | Excess return | Volatility | Sharpe (95% interval) | Max drawdown | Turnover per year | Bonds, average weight |")
    L.append("|---|---|---|---|---|---|---|")
    for n in ORDER:
        r = summ[n]
        to = f"{r['turnover_ann']:.1f}x" if "turnover_ann" in r else "n/a"
        bw = pct(r["avg_bonds"], 0) if "avg_bonds" in r else "n/a"
        L.append(f"| {n} | {pct(r['ann_excess'])} | {pct(r['ann_vol'])} | {r['sharpe']:.2f} ({r['sharpe_lo']:.2f} to "
                 f"{r['sharpe_hi']:.2f}) | {pct(r['max_drawdown'], 0)} | {to} | {bw} |")
    L.append("")
    L.append("**Value added over 1/N**, the portfolio every forecast strategy starts from")
    L.append("")
    L.append("| Views | Active return | Tracking error | Information ratio | t | Sharpe difference (95% interval) | p | Deflated Sharpe Ratio |")
    L.append("|---|---|---|---|---|---|---|---|")
    diffs = {d["a"]: d for d in m["sharpe_diffs"] if d["b"] == "1/N"}
    for n in FORECAST:
        a, d = m["active"][n], diffs[n]
        L.append(f"| {n} | {pct(a['active_return_ann'])} | {pct(a['tracking_error_ann'])} | {a['info_ratio']:.2f} | "
                 f"{a['t_stat']:.2f} | {d['diff']:+.2f} ({d['lo']:+.2f} to {d['hi']:+.2f}) | {d['p_value']:.2f} | {a['dsr']:.2f} |")
    am = m["active_meta"]
    L.append("")
    L.append(f"Active return is the monthly return minus the 1/N return ({am['n_months']} months). The Deflated Sharpe "
             f"Ratio is the probability that the true information ratio beats the best of {am['n_trials']} skill-free "
             f"trials (hurdle {am['sr0_annual']:.2f} a year); above 0.95 would be evidence of skill.")
    L.append("")
    L.append("**Forecast skill**: rank correlation across assets between each score and next month's volatility-scaled return")
    L.append("")
    L.append("| Score | Mean IC | Newey-West t | p | Months positive |")
    L.append("|---|---|---|---|---|")
    for n in ["Momentum", "ML ridge", "ML gradient boosting", "ML", "Low volatility", "Momentum, equities only",
              "ML, equities only", "ML minus Momentum", "ML minus Low volatility"]:
        r = m["ic"][n]
        L.append(f"| {n} | {r['mean']:.3f} | {r['t_stat']:.2f} | {r['p_value']:.3f} | {pct(r['share_positive'], 0)} |")
    ml = m["ic"]["ML"]
    L.append("")
    L.append(f"{ml['n']} months per row. With the observed month to month dispersion of the ML IC ({ml['std']:.2f}), "
             f"a mean IC below {ml['detectable_ic']:.3f} could not reach t = 2 in this sample. The ML and momentum "
             f"scores have a rank correlation of {m['score_corr_ml_momentum']:.2f}.")
    L.append("")
    L.append("**By period**")
    L.append("")
    labs = list(m["periods"])
    L.append("| | " + " | ".join(labs) + " |")
    L.append("|---|" + "---|" * len(labs))
    for n in ORDER:
        L.append(f"| Sharpe, {n} | " + " | ".join(f"{m['periods'][p][n]:.2f}" for p in labs) + " |")
    for n in ("Momentum", "ML"):
        L.append(f"| Mean IC, {n} | " + " | ".join(f"{m['ic_periods'][p][n]:.3f}" for p in labs) + " |")
    L.append("")
    L.append("**Robustness**: Sharpe ratio when one assumption changes")
    L.append("")
    rb = m["robustness"]
    cols = ["1/N"] + FORECAST
    L.append("| Change | " + " | ".join(cols) + " |")
    L.append("|---|" + "---|" * len(cols))
    L.append("| Base case | " + " | ".join(f"{summ[n]['sharpe']:.2f}" for n in cols) + " |")
    for lab in rb:
        L.append(f"| {lab[0].upper() + lab[1:]} | " + " | ".join(f"{rb[lab][n]:.2f}" if n in rb[lab] else "same" for n in cols) + " |")
    ct = m["carry_timing"]
    L.append("")
    L.append(f"Bond carry as a timing signal: regressing next month's volatility-scaled excess return of the three bond "
             f"series on the carry z-score gives a slope of {ct['slope']:.3f} (t = {ct['t_stat']:.2f}, p = {ct['p_value']:.3f}, "
             f"{ct['n_obs']} observations, standard errors clustered by month).")
    return "\n".join(L)


def fill(text: str, name: str, body: str) -> str:
    start, end = MARK.format(name=name), END.format(name=name)
    a, b = text.index(start) + len(start), text.index(end)
    return text[:a] + "\n" + body + "\n" + text[b:]


def main() -> None:
    readme = ROOT / "README.md"
    text = readme.read_text()
    m = load()
    new = fill(fill(text, "headline", headline(m)), "results", render(m))
    if "--check" in sys.argv:
        if new != text:
            print("README is out of date; run python scripts/render_readme.py")
            sys.exit(1)
        print("README matches results/metrics.json")
        return
    readme.write_text(new)
    print("README rendered")


if __name__ == "__main__":
    main()
