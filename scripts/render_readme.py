"""Render the README Results block from results/metrics.json.

    python scripts/render_readme.py          rewrite the block
    python scripts/render_readme.py --check  exit 1 if the README is stale
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
START = "<!-- results:start (generated by scripts/render_readme.py, do not edit by hand) -->"
END = "<!-- results:end -->"

PCT = {"Ann. Return", "Ann. Volatility", "Max Drawdown", "Alpha (ann.)"}
ROWS = ["Ann. Return", "Ann. Volatility", "Sharpe Ratio", "Sortino Ratio",
        "Max Drawdown", "Beta", "Alpha (ann.)"]


def fmt(k: str, d: dict) -> str:
    if k not in d:
        return "n/a"
    v = d[k]
    return f"{v:.2%}" if k in PCT else f"{v:.3f}"


def block() -> str:
    m = json.loads((ROOT / "results" / "metrics.json").read_text())
    s, a, b, t, ic = m["strategy"], m["ablation_bl_only"], m["spy"], m["tests"], m["ic"]
    lines = [
        START,
        f"Sample: {m['sample']['first_day']} to {m['sample']['last_day']} "
        f"({m['sample']['n_days']} trading days), monthly rebalance, "
        f"{m['config']['train_window']}-day training window, {m['config']['horizon']}-day forecast horizon.",
        "",
        "| Metric | ML + BL Strategy | BL-only (ablation) | SPY |",
        "|---|---|---|---|",
    ]
    lines += [f"| {k} | {fmt(k, s)} | {fmt(k, a)} | {fmt(k, b)} |" for k in ROWS]
    lines += [
        "",
        f"- Effect of the ML views (ML + BL minus BL-only): Sharpe {s['Sharpe Ratio'] - a['Sharpe Ratio']:+.3f}, "
        f"annual return {s['Ann. Return'] - a['Ann. Return']:+.2%}.",
        f"- Block-bootstrap Sharpe test: SR {t['bootstrap_sharpe']:.3f}, p = {t['bootstrap_p']:.3f}.",
        f"- Deflated Sharpe Ratio: {t['dsr']:.3f} against a threshold of {t['dsr_threshold']:.3f} "
        f"(n_trials = {t['dsr_n_trials']}).",
        f"- Cross-fitted out-of-fold IC over {ic['n_asset_rebalances']} asset-rebalance pairs: "
        f"mean {ic['mean']:.3f}, median {ic['median']:.3f}, positive in {ic['share_positive']:.0%}. "
        "Only assets with positive IC at a rebalance send a view to Black-Litterman. "
        "Per-asset values are in results/ic_summary.csv.",
        END,
    ]
    return "\n".join(lines)


def main() -> int:
    text = README.read_text()
    pat = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pat.search(text):
        print("results markers not found in README.md", file=sys.stderr)
        return 1
    new = pat.sub(lambda _: block(), text)
    if "--check" in sys.argv:
        if new != text:
            print("README Results block is stale: run make reproduce", file=sys.stderr)
            return 1
        print("README Results block matches results/metrics.json")
        return 0
    README.write_text(new)
    return 0


if __name__ == "__main__":
    sys.exit(main())
