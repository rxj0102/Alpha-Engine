"""Render the README Results block from results/metrics.json.

    python scripts/render_readme.py          rewrite the block
    python scripts/render_readme.py --check  exit 1 if the README is stale
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
START = "<!-- results:start (generated by scripts/render_readme.py, do not edit by hand) -->"
END = "<!-- results:end -->"

ROWS = [("ann_return", "Ann. return", "pct"), ("ann_vol", "Ann. volatility", "pct"),
        ("sharpe", "Sharpe ratio", "num"), ("sortino", "Sortino ratio", "num"),
        ("max_drawdown", "Max drawdown", "pct"), ("beta", "Beta to market", "num"),
        ("alpha_ann", "Alpha (ann.)", "pct")]
ORDER = ["ML + BL", "BL only", "1/N equal weight", "US market (SPY stand-in)"]


def fmt(d: dict, k: str, kind: str) -> str:
    if k not in d or d[k] is None:
        return "n/a"
    return f"{d[k]:.2%}" if kind == "pct" else f"{d[k]:.3f}"


def block() -> str:
    m = json.loads((ROOT / "results" / "metrics.json").read_text())
    c, t, ic, live = m["comparison"], m["tests"], m["ic_in_training"], m["ic_live"]
    names = [n for n in ORDER if n in c]
    s, base = c["ML + BL"], c.get("1/N equal weight", {})
    lines = [
        START,
        f"Evaluated from the first rebalance, {m['sample']['first_day']} to {m['sample']['last_day']} "
        f"({m['sample']['n_days']} trading days), with the same universe, monthly rebalance and costs "
        f"for every strategy. {m['config']['train_window']}-day training window, "
        f"{m['config']['horizon']}-day forecast horizon, {len(m['config']['universe'])} assets.",
        "",
        "| Metric | " + " | ".join(names) + " |",
        "|---|" + "---|" * len(names),
    ]
    lines += [f"| {label} | " + " | ".join(fmt(c[n], k, kind) for n in names) + " |" for k, label, kind in ROWS]
    lines += [""]
    if "BL only" in c:
        a = c["BL only"]
        lines.append(f"- Effect of the ML views (ML + BL minus BL only): Sharpe {s['sharpe'] - a['sharpe']:+.3f}, "
                     f"annual return {s['ann_return'] - a['ann_return']:+.2%}.")
    if base:
        lines.append(f"- Against the 1/N baseline: Sharpe {s['sharpe'] - base['sharpe']:+.3f}, "
                     f"annual return {s['ann_return'] - base['ann_return']:+.2%}.")
    lines += [
        f"- Block-bootstrap Sharpe test: SR {t['bootstrap_sharpe']:.3f}, p = {t['bootstrap_p']:.3f}.",
        f"- Deflated Sharpe ratio (observed Sharpe divided by the multiple-testing threshold "
        f"{t['dsr_threshold']:.3f} for {t['dsr_n_trials']} trials; above 1 is significant): {t['dsr']:.3f}.",
        f"- Live cross-sectional IC (forecast at each rebalance against the next {m['config']['horizon']} days, "
        f"{live['n_rebalances']} non-overlapping rebalances): mean {live['mean']:.3f}, ICIR {live['icir']:.2f}, "
        f"t = {live['t_stat']:.2f}, p = {live['p_value']:.3f}. Values per rebalance are in results/live_ic.csv.",
        f"- In-training out-of-fold IC (diagnostic, non-overlapping rows, {ic['n_asset_rebalances']} "
        f"asset-rebalance pairs): mean {ic['mean']:.3f}, median {ic['median']:.3f}, positive in "
        f"{ic['share_positive']:.0%}. Only assets with positive IC at a rebalance send a view to Black-Litterman.",
        END,
    ]
    return "\n".join(lines)


def main() -> int:
    text = README.read_text()
    pat = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pat.search(text):
        print("results markers not found in README.md", file=sys.stderr)
        return 1
    new = pat.sub(lambda _: block(), text)
    if "--check" in sys.argv:
        if new != text:
            print("README Results block is stale: run make reproduce", file=sys.stderr)
            return 1
        print("README Results block matches results/metrics.json")
        return 0
    README.write_text(new)
    return 0


if __name__ == "__main__":
    sys.exit(main())
